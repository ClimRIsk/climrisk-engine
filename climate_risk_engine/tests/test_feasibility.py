import pytest

from cri.resident import feasibility as FE, knowledge as K


def test_matches_building_cost_question_but_not_tool_requests():
    assert FE.matches("can I build a 10 story building at 22.2645, 91.805? what would the cost be?")
    assert FE.matches("what would a ten-storey tower cost to build here")
    assert not FE.matches("build a 3D twin of 22.2645, 91.805")
    assert not FE.matches("how much does cement cost")
    assert FE.storeys("a 10 story building") == 10 and FE.storeys("twelve floors") == 12


def test_analyse_keeps_null_unknown_and_never_prices():
    rep = {"overall_rating": "MODERATE", "zones": [
        {"key": "earthquake", "title": "Earthquake", "rating": "HIGH"},
        {"key": "river_flood", "title": "River flooding", "rating": "NEGLIGIBLE"},
        {"key": "cyclone", "title": "Cyclone wind", "rating": None},
        {"key": "heat", "title": "Heat", "rating": "MODERATE"}]}
    a = FE.analyse(rep, 10)
    assert [d["hazard"] for d in a["drivers"]] == ["Earthquake", "Heat"]
    assert a["not_assessed"] == ["Cyclone wind"]
    assert a["height"] == "about 32 m"
    txt = FE.reply_text(a, "test site")
    assert "can't put a price" in txt and "$" not in txt and "€" not in txt


def test_wikis_are_not_trusted_and_are_purged(tmp_path, monkeypatch):
    monkeypatch.setenv("CRI_RESIDENT_DIR", str(tmp_path))
    assert not K.trusted("https://en.wikipedia.org/wiki/Flood")
    assert K.trusted("https://www.nhc.noaa.gov/surge/")
    assert not K.learn_url("https://en.wikipedia.org/wiki/Flood")["ok"]
    K._store("https://en.wikipedia.org/wiki/Flood", "Flood (Wikipedia)", "wikipedia", ["A flood is an overflow of water that submerges land that is normally dry " * 3])
    K._store("https://www.nhc.noaa.gov/surge/", "NOAA NHC: Storm surge", "primary", ["Storm surge is an abnormal rise of water generated by a storm over and above the predicted astronomical tide " * 2])
    K._PURGED["done"] = False
    assert K.purge_untrusted() >= 1
    assert all("wikipedia" not in h["url"] for h in K.search("flood water tide storm"))


def test_learn_topic_never_falls_back_to_a_wiki(monkeypatch):
    monkeypatch.delenv("CRI_STORY_OFFLINE", raising=False)
    monkeypatch.setattr(K, "learn_url", lambda *a, **k: {"ok": False, "error": "x"})
    r = K.learn_topic("quantum chromodynamics lattice")
    assert not r["ok"] and "wiki" in r["error"]
    assert all("wikipedia" not in u for _, u, _ in K.PRIMARY)
