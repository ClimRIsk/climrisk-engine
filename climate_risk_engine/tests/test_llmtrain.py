def test_qa_and_refuse_examples(tmp_path):
    corpus = tmp_path / "corpus.jsonl"
    rng = random.Random(0)
    sents = ["Storm surge is the abnormal rise of water generated by a storm over and above the predicted astronomical tide.",
             "The surge height depends on wind speed, storm size, forward speed and the shape of the coastline and sea floor.",
             "Low pressure at the centre of the storm adds a small rise but wind is the dominant cause of the surge.",
             "Surge can flood coastal assets far inland when it arrives at high tide and is carried by waves."]
    other = ["Drought is a prolonged period of abnormally low rainfall that leads to a shortage of water for people and industry.",
             "Agricultural drought affects crop yields while hydrological drought reduces river flows and reservoir storage in a basin.",
             "Cooling water availability for power plants falls during drought and can force plants to cut their output.",
             "Heat and drought often occur together which raises demand for water and electricity at the same time."]
    rows = []
    for i in range(30):
        uniq = "".join(chr(97 + (i * 7 + k * 3) % 26) for k in range(7))
        for name, ss in (("surge", sents), ("drought", other)):
            rows.append({"url": f"http://x/{name}{i}", "title": f"NOAA: {name} {i}", "licence": "public domain", "topic": "hazard", "train": True, "ok": True,
                         "passages": [" ".join(ss) + " " + " ".join(f"The {uniq} basin shows extra {uniq} behaviour number {j} that gives more context for this passage." for j in range(3))]})
    corpus.write_text("\n".join(json.dumps(r) for r in rows))
    ps = D.load_passages(tmp_path)
    assert ps
    D._keyterms(ps)
    qa = D.build_qa(ps, rng, per=1)
    assert qa
    for r in qa:
        ans = r["messages"][2]["content"]
        cites = {int(x) for x in re.findall(r"\[(\d+)\]", ans)}
        assert cites == {r["meta"]["target"]}
    rf = D.build_refuse(ps, rng, 20)
    for r in rf:
        assert E.score({"kind": "refuse", "meta": r["meta"], "messages": r["messages"]}, r["messages"][2]["content"])["says_missing"] == 1.0


def test_case_library_is_consistent():
    from cri.llmtrain import cases as CS
    from cri.llmtrain.cases_data import CASES
    ids = [c["id"] for c in CASES]
    assert len(ids) == len(set(ids)) >= 24
    for c in CASES:
        assert c["sources"] and c["facts"] and c["gaps"] and c["lessons"], c["id"]
        for _, si in c["facts"]:
            assert si < len(c["sources"]), c["id"]
        for _, _, si in c["responses"]:
            assert si < len(c["sources"]), c["id"]
        for ch in c["channels"]:
            assert ch in CS.CH_DESC, (c["id"], ch)
        for lesson in c["lessons"]:
            assert not re.search(r"\d", lesson), (c["id"], lesson)      # lessons are analysis: no numbers
    assert {"basf-rhine-2018", "panama-2023", "tsmc-2021", "valencia-2024", "rs-brazil-2024", "kariba-2024", "ian-2022", "uri-2021"} <= set(CS.HELD_OUT) & set(ids)


def _nums(t):
    return {x.replace(",", "").rstrip(".").lstrip("0") or "0" for x in re.findall(r"\d[\d,]*\.?\d*", t)}


def test_case_rows_are_correct_by_construction_and_do_not_leak():
    from cri.llmtrain import cases as CS
    for seed in range(3):
        rows = CS.build({}, seed=seed, allow_unverified=True)
        assert len(rows) > 300
        for r in rows:
            u, a = r["messages"][1]["content"], r["messages"][2]["content"]
            assert _nums(a) <= _nums(u), (r["meta"], _nums(a) - _nums(u))
            cites = {int(x) for x in re.findall(r"\[(\d+)\]", a)}
            assert not cites or max(cites) <= r["meta"]["n"]
            if r["kind"] == "case_gap":
                assert E.MISSING.search(a)
            if r["split"] != "test":
                for h in [x for x in CS.HELD_OUT if x in CS.SHORT]:
                    assert CS.SHORT[h] not in u, (h, r["meta"])


def test_edgar_rows_use_only_quoted_text(tmp_path):
    import json as _j
    from cri.llmtrain import edgar_cases as EC
    recs = []
    for ev in ("ida-2021", "uri-2021", "camp-2018"):
        for k in range(6):
            recs.append({"event": ev, "event_name": ev.upper(), "hazard": "x", "region": "y", "company": f"{ev[:3].title()}Co{k} Inc", "cik": f"{ev[:3]}{k}", "form": "8-K", "filed": "2021-09-01",
                         "url": f"http://x/{ev}{k}", "quotes": [{"quote": f"{ev[:3].title()}Co{k} recorded a ${k + 2} million loss from {ev.upper()} and drew on its revolving credit facility.", "amounts": [f"${k + 2} million"], "response": ["financial"]}]})
    p = tmp_path / "edgar_cases.jsonl"
    p.write_text("\n".join(_j.dumps(r) for r in recs))
    rows = EC.build_rows(p, per_case=2)
    assert rows
    for r in rows:
        u, a = r["messages"][1]["content"], r["messages"][2]["content"]
        assert _nums(a) <= _nums(u)
        cites = {int(x) for x in re.findall(r"\[(\d+)\]", a)}
        assert not cites or max(cites) <= r["meta"]["n"]
    assert any(r["kind"] == "case_gap" for r in rows)


