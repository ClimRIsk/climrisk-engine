"""
Run the scenario suite and write docs/SCENARIO_REPORT.md: for every scenario, the perils that matter and what the engine has for each, plus the ranking of gaps across scenarios.

  python scripts/run_scenarios.py            (offline contract checks; no network)

The live event checks are separate (scripts/validate_scenario_events.py) and their results are read from data/backtest/scenario_events_validation.json if present.
"""
from __future__ import annotations

import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from cri import perilscope as P          # noqa: E402
from cri import scenario_suite as SS     # noqa: E402

OUT = ROOT / "docs" / "SCENARIO_REPORT.md"
EV = ROOT / "data" / "backtest" / "scenario_events_validation.json"


def main() -> None:
    sc = SS.scenarios()
    rows, gap_count, gap_cases, status_count, in_price = [], Counter(), defaultdict(list), Counter(), Counter()
    for s in sc:
        r = SS.check_offline(s, n_years=300)
        site = r["result"]["sites"][0]
        sm = site["peril_scope"]["summary"]
        rows.append((s, r, site))
        for p in site["peril_scope"]["perils"]:
            if p["role"] == "primary":
                status_count[p["engine_status"]] += 1
                in_price["yes" if p["in_price"] else "no"] += 1
                if p["engine_status"] in ("none", "screen", "hazard_only"):
                    gap_count[(p["peril"], p["engine_status"])] += 1
                    gap_cases[p["peril"]].append(s["id"])
    L = ["# Scenario report", "",
         "Generated by `scripts/run_scenarios.py` from `cri.scenario_suite`. Offline contract checks: nothing is silently left out of a number, scope is stated, nulls are explained. Magnitudes are not tested here; see the event checks at the end.", "",
         f"{len(sc)} scenarios, {sum(len(s['sites']) for s in sc)} sites. Contract checks passed: {sum(1 for _, r, _ in rows if r['passed'])} of {len(sc)}.", "",
         "## What the engine has for the primary perils of these scenarios", "",
         "| Engine status | Primary peril occurrences | Meaning |", "|---|---|---|"]
    tot = sum(status_count.values())
    mean = {"loss_model": "a hazard and a loss path exist", "hazard_only": "a hazard value exists, nothing converts it to loss", "screen": "a proxy only", "none": "nothing"}
    for k in ("loss_model", "hazard_only", "screen", "none"):
        L.append(f"| {k} | {status_count[k]} ({100 * status_count[k] / tot:.0f} %) | {mean[k]} |")
    L += ["", f"Primary perils actually inside the quoted number in these runs (these offline runs supply a cyclone rate where the basin has one and no flood map, as in much of the world, so this is a floor and not a forecast of any real run): {in_price['yes']} of {in_price['yes'] + in_price['no']}.", "",
          "## Gaps ranked by how many scenarios they affect", "", "| Peril | Engine status | Scenarios affected | Which |", "|---|---|---|---|"]
    for (p, st), n in sorted(gap_count.items(), key=lambda kv: (-kv[1], kv[0])):
        L.append(f"| {p} | {st} | {n} | {', '.join(gap_cases[p][:8])}{' ...' if len(gap_cases[p]) > 8 else ''} |")
    L += ["", "## Scenarios", ""]
    for s, r, site in rows:
        sm = site["peril_scope"]["summary"]
        L += [f"### {s['title']}", "", f"Client: {s['client']}. Sector read as `{sm['sector']}`, regions {sm['regions']}. Question: {s['question']}", "",
              f"{sm['statement']}", "", "| Peril | Role | Engine | In the number | Why it matters |", "|---|---|---|---|---|"]
        for p in site["peril_scope"]["perils"]:
            L.append(f"| {p['peril']} | {p['role']} | {p['engine_status']} | {'yes' if p['in_price'] else 'no'} | {p['why'].replace('src: ', '').replace('judgement: ', '(judgement) ')[:150]} |")
        if s["reference"]:
            L += ["", f"Reference: {s['reference']['event']} ({s['reference']['src']})."]
        if r["findings"]:
            L += ["", "Contract findings:"] + [f"- {f['check']}: {f['finding']}" for f in r["findings"]]
        L.append("")
    if EV.exists():
        ev = json.loads(EV.read_text())
        L += ["## Event checks: does the hazard layer recognise real events?", "", "| Event | Variable | Event value | Result | Expectation | Passed |", "|---|---|---|---|---|---|"]
        for k, e in ev.items():
            if "error" in e:
                L.append(f"| {k} | | | could not be fetched | | |")
                continue
            res = e.get("return_period_years", e.get("rank_in_record", e.get("percentile_of_event_day", e.get("event_value"))))
            L.append(f"| {e['event']} | {e['variable']} | {e.get('event_value')} | {res} ({e.get('source') or ''}) | {e['expectation']} | {e['passed']} |")
        L.append("")
    OUT.write_text("\n".join(L))
    print("wrote", OUT)
    print({k: v for k, v in status_count.items()})
    for (p, st), n in sorted(gap_count.items(), key=lambda kv: (-kv[1], kv[0]))[:12]:
        print(f"{n:3d}  {p}  [{st}]")


if __name__ == "__main__":
    main()
